import { createHash } from 'node:crypto';
import { countSegments } from '@fsc/connectors';
import { MOCK_LOCAL_PASSWORD, PORTAL_USERS, TENANTS } from './catalog.js';
import { mockUuid } from './ids.js';
import { CONTACTS, LEADS } from './scenarios.js';
import type { MockLead, MockRequest } from './schemas.js';

/**
 * Renders the catalog as `supabase/seed/NN_<name>.sql`. Output is deterministic: IDs come from
 * scenario keys and times are `now()` at load, so the same catalog always produces the same files.
 */

export const tenantId = (key: string) => mockUuid('tenant', key);
export const authUserId = (key: string) => mockUuid('auth-user', key);
export const portalUserId = (key: string) => mockUuid('portal-user', key);
export const contactId = (key: string) => mockUuid('contact', key);
export const leadId = (key: string) => mockUuid('lead', key);
export const eventId = (key: string) => mockUuid('inbound-event', key);
export const requestId = (key: string) => mockUuid('request', key);

const GENERATED =
  '-- Generated by `npm run seed:build` from packages/mock-data. Do not edit by hand.\n' +
  '-- Local only (docs/engineering/DATABASE.md). Values follow docs/product/MOCK_DATA.md.\n';

/** SQL string literal. Catalog values are validated, but quoting never depends on that. */
function lit(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

function rows(values: string[][]): string {
  return values.map((v) => `  (${v.join(', ')})`).join(',\n');
}

const opt = (value: string | undefined) => (value === undefined ? 'null' : lit(value));
const ago = (minutes: number) => `now() - interval '${minutes} minutes'`;
/** Slot starts land on the hour so the calendar views look like real bookings. */
const slotAt = (hours: number, plus = 0) =>
  `date_trunc('hour', now()) + interval '${hours + plus} hours'`;

function find<T extends { key: string }>(list: readonly T[], key: string): T {
  const item = list.find((x) => x.key === key);
  if (!item) throw new Error(`Unknown catalog key ${key}`);
  return item;
}

/** The provider event that started each lead, as the intake path would have recorded it. */
function firstEvent(lead: MockLead) {
  const byKind = {
    missed_call: { source: 'phone', kind: 'missed_call', prefix: 'MOCK-CA' },
    text: { source: 'phone', kind: 'text_received', prefix: 'MOCK-SM-IN' },
    email: { source: 'email', kind: 'email_received', prefix: 'MOCK-EM-IN' },
    form: { source: 'form', kind: 'form_submitted', prefix: 'MOCK-FORM' },
  } as const;
  const event = byKind[lead.source];
  const externalId = `${event.prefix}-${lead.key}`;
  return { ...event, externalId, sha256: createHash('sha256').update(externalId).digest('hex') };
}

function tenantsFile(): string {
  return `${GENERATED}
-- Tenants. Config, playbooks and service registrations follow with the settings migration.
insert into app.tenants (id, slug, name, status, timezone) values
${rows(TENANTS.map((t) => [lit(tenantId(t.key)), lit(t.slug), lit(t.name), lit(t.status), lit(t.timezone)]))};
`;
}

function portalUsersFile(): string {
  const authUsers = PORTAL_USERS.map((u) => [
    lit('00000000-0000-0000-0000-000000000000'),
    lit(authUserId(u.key)),
    lit('authenticated'),
    lit('authenticated'),
    lit(u.email),
    `extensions.crypt(${lit(MOCK_LOCAL_PASSWORD)}, extensions.gen_salt('bf'))`,
    'now()',
    lit('{"provider":"email","providers":["email"]}'),
    lit(JSON.stringify({ name: u.name })),
    'now()',
    'now()',
    // Supabase Auth reads these as strings and fails on null.
    "''",
    "''",
    "''",
    "''",
  ]);
  const identities = PORTAL_USERS.map((u) => [
    lit(mockUuid('auth-identity', u.key)),
    lit(authUserId(u.key)),
    lit(authUserId(u.key)),
    lit('email'),
    lit(JSON.stringify({ sub: authUserId(u.key), email: u.email, email_verified: true })),
    'now()',
    'now()',
    'now()',
  ]);
  const portalUsers = PORTAL_USERS.map((u) => [
    lit(portalUserId(u.key)),
    lit(tenantId(u.tenant)),
    lit(authUserId(u.key)),
    lit(u.role),
    lit(u.name),
    lit(u.mobile),
  ]);

  return `${GENERATED}
-- Local Supabase Auth logins. Every mock user signs in with the password
-- ${lit(MOCK_LOCAL_PASSWORD)}, which exists only here and works only against the local stack.
insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change, email_change_token_new
) values
${rows(authUsers)};

insert into auth.identities (
  id, user_id, provider_id, provider, identity_data, last_sign_in_at, created_at, updated_at
) values
${rows(identities)};

-- Portal users: owner and staff per tenant (Old Mill is disabled, so its owner cannot sign in).
insert into app.portal_users (id, tenant_id, auth_user_id, role, display_name, mobile) values
${rows(portalUsers)};
`;
}

function contactsFile(): string {
  const values = CONTACTS.map((c) => [
    lit(contactId(c.key)),
    lit(tenantId(c.tenant)),
    opt(c.name),
    lit(c.phone),
    opt(c.email),
  ]);
  return `${GENERATED}
-- Contacts: one per person per tenant, matched by phone or email.
insert into app.contacts (id, tenant_id, display_name, phone, email) values
${rows(values)};
`;
}

function inboundEventsFile(): string {
  const values = LEADS.map((l) => {
    const e = firstEvent(l);
    return [
      lit(eventId(l.key)),
      lit(tenantId(l.tenant)),
      lit(e.source),
      lit(e.kind),
      lit(e.externalId),
      lit(e.sha256),
      ago(l.minutesAgo),
    ];
  });
  return `${GENERATED}
-- The provider event that started each scenario lead.
insert into app.inbound_events (
  id, tenant_id, source, kind, external_event_id, payload_sha256, received_at
) values
${rows(values)};
`;
}

function leadsFile(): string {
  const touched = (l: MockLead) => ago(Math.max(l.minutesAgo - 5, 0));
  const leads = LEADS.map((l) => [
    lit(leadId(l.key)),
    lit(tenantId(l.tenant)),
    lit(contactId(l.contact)),
    lit(l.source),
    lit(l.state),
    opt(l.reason),
    opt(l.urgency),
    opt(l.category),
    lit(l.summary),
    opt(l.address),
    lit(eventId(l.key)),
    touched(l),
    ago(l.minutesAgo),
    touched(l),
  ]);
  const calls = LEADS.filter((l) => l.source === 'missed_call').map((l) => [
    lit(mockUuid('call', l.key)),
    lit(tenantId(l.tenant)),
    lit(leadId(l.key)),
    lit(firstEvent(l).externalId),
    lit(find(CONTACTS, l.contact).phone),
    lit(find(TENANTS, l.tenant).connectNumber),
    ago(l.minutesAgo),
  ]);
  const voicemails = LEADS.flatMap((l) =>
    l.voicemail
      ? [
          [
            lit(mockUuid('voicemail', l.key)),
            lit(tenantId(l.tenant)),
            lit(mockUuid('call', l.key)),
            lit(`MOCK-RE-${l.voicemail.code}`),
            String(l.voicemail.seconds),
            lit(l.voicemail.transcript),
            l.voicemail.confidence.toFixed(3),
            ago(l.minutesAgo),
          ],
        ]
      : [],
  );
  return `${GENERATED}
-- Scenario leads, their missed calls and voicemail transcripts (the evaluation set).
insert into app.leads (
  id, tenant_id, contact_id, source, state, state_reason, urgency, category, summary, address,
  first_event_id, state_changed_at, created_at, updated_at
) values
${rows(leads)};

insert into app.calls (
  id, tenant_id, lead_id, provider_call_id, from_number, to_number, started_at
) values
${rows(calls)};

insert into app.voicemails (
  id, tenant_id, call_id, recording_ref, duration_seconds, transcript, transcript_confidence,
  created_at
) values
${rows(voicemails)};
`;
}

function conversationsFile(): string {
  const threads = LEADS.filter((l) => l.messages !== undefined);
  const conversations = threads.map((l) => [
    lit(mockUuid('conversation', l.key)),
    lit(tenantId(l.tenant)),
    lit(leadId(l.key)),
    lit('sms'),
    ago(l.minutesAgo),
  ]);
  const messages = threads.flatMap((l) =>
    (l.messages ?? []).map((m, i) => [
      lit(mockUuid('message', `${l.key}:${i}`)),
      lit(tenantId(l.tenant)),
      lit(mockUuid('conversation', l.key)),
      lit(m.direction),
      lit(m.direction === 'in' ? 'customer' : 'template'),
      opt(m.template),
      lit(m.body),
      String(countSegments(m.body).segments),
      lit(`MOCK-SM-${l.key}-${i + 1}`),
      lit(m.direction === 'in' ? 'received' : 'delivered'),
      ago(m.minutesAgo),
    ]),
  );
  return `${GENERATED}
-- Text threads (MOCK_DATA.md, Conversation scripts). Outbound text always names its template.
insert into app.conversations (id, tenant_id, lead_id, channel, created_at) values
${rows(conversations)};

insert into app.messages (
  id, tenant_id, conversation_id, direction, author, template_key, body, segments,
  provider_message_id, delivery_status, occurred_at
) values
${rows(messages)};
`;
}

function requestsFile(): string {
  const withRequest = LEADS.flatMap((l) => (l.request ? [{ lead: l, request: l.request }] : []));
  const decided = (r: MockRequest) => r.decidedBy !== undefined;
  const requests = withRequest.map(({ lead, request: r }) => [
    lit(requestId(lead.key)),
    lit(tenantId(lead.tenant)),
    lit(leadId(lead.key)),
    slotAt(r.slotInHours),
    slotAt(r.slotInHours, 1),
    lit(r.state),
    r.decidedBy ? lit(portalUserId(r.decidedBy)) : 'null',
    opt(r.decidedVia),
    decided(r) ? ago(Math.max(lead.minutesAgo - 30, 1)) : 'null',
    ago(Math.max(lead.minutesAgo - 10, 0)),
  ]);
  const holds = withRequest.flatMap(({ lead, request: r }) =>
    r.hold
      ? [
          [
            lit(mockUuid('hold', lead.key)),
            lit(tenantId(lead.tenant)),
            lit(requestId(lead.key)),
            lit(`MOCK-GCAL-${lead.tenant}`),
            lit(`MOCK-CAL-${lead.key}`),
            slotAt(r.slotInHours),
            slotAt(r.slotInHours, 1),
            lit(r.hold),
            r.hold === 'active' ? "now() + interval '22 hours'" : ago(60),
          ],
        ]
      : [],
  );
  return `${GENERATED}
-- Requests in decided and undecided states, with their calendar holds.
insert into app.requests (
  id, tenant_id, lead_id, slot_start, slot_end, state, decided_by, decided_via, decided_at,
  created_at
) values
${rows(requests)};

insert into app.calendar_holds (
  id, tenant_id, request_id, calendar_id, provider_hold_ref, slot_start, slot_end, state,
  expires_at
) values
${rows(holds)};
`;
}

/** Seed file name → contents, in load order. */
export function buildSeedFiles(): Map<string, string> {
  return new Map([
    ['01_tenants_and_config.sql', tenantsFile()],
    ['02_portal_users.sql', portalUsersFile()],
    ['05_contacts.sql', contactsFile()],
    ['06_inbound_events.sql', inboundEventsFile()],
    ['07_leads_calls_voicemails.sql', leadsFile()],
    ['08_conversations_messages.sql', conversationsFile()],
    ['09_requests_and_holds.sql', requestsFile()],
  ]);
}
